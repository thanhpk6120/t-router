// Regenerates src/shared/utils/providerIconManifest.js from the bundled marks
// in public/providers. ProviderIcon asks this manifest before requesting
// `/providers/<id>.png`, so a custom provider (e.g. "ViLao") no longer fires a
// 404 for an icon that was never bundled.
//
// Runs from `predev` / `prebuild`; run it by hand with:
//   node scripts/gen-provider-icon-manifest.mjs
import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const iconDir = join(root, "public", "providers");
const outFile = join(root, "src", "shared", "utils", "providerIconManifest.js");

const files = await readdir(iconDir, { withFileTypes: true });
const ids = [...new Set(
  files
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith(".png"))
    .map((entry) => entry.name.slice(0, -4).toLowerCase()),
)].sort();

const body = `// AUTO-GENERATED by scripts/gen-provider-icon-manifest.mjs — do not edit.
// Every bundled mark under public/providers (file basename, lowercased).
// ProviderIcon only requests /providers/<id>.png when <id> is listed here, so
// custom providers never fire a 404 for a mark that does not exist.
// Regenerate with: node scripts/gen-provider-icon-manifest.mjs
export const PROVIDER_ICON_IDS = [
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
];
`;

await writeFile(outFile, body, "utf8");
console.log(`[provider-icons] wrote ${ids.length} ids to ${outFile.replace(root, ".")}`);
